#!/usr/bin/env node
// Regenerate the self-hosted icon font.
//
// Run this whenever an icon is added, removed or renamed:
//     npm run icons:build
//
// It reads the icon set out of the source rather than from a hand-kept list, subsets Font Awesome Free 6.5.1 Solid to exactly those glyphs, and writes the font, the stylesheet and a manifest.
// `tests/icons.test.ts` fails if the committed output does not match what this produces, so forgetting to run it is caught rather than shipped.

import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative } from 'node:path';
import subsetFont from 'subset-font';
import {
  FA_SOLID_WOFF2,
  OUT_CSS,
  OUT_FONT,
  OUT_MANIFEST,
  REPO_ROOT,
  resolveIcons,
} from './icons/scan.mjs';

const { resolved, missing, glyphs } = resolveIcons();

if (missing.size > 0) {
  console.error('\nThese classes have no glyph in Font Awesome Free 6.5.1:\n');
  for (const [name, sites] of missing) {
    console.error(`  ${name}`);
    for (const site of sites) console.error(`      ${site}`);
  }
  console.error(
    '\nA Pro-only icon renders as an empty box with no error. Pick a Free equivalent.\n'
  );
  process.exit(1);
}

const source = readFileSync(FA_SOLID_WOFF2);
const text = glyphs.map((cp) => String.fromCodePoint(parseInt(cp, 16))).join('');

const subset = await subsetFont(source, text, { targetFormat: 'woff2' });

mkdirSync(dirname(OUT_FONT), { recursive: true });
writeFileSync(OUT_FONT, subset);

const byName = [...resolved].sort(([a], [b]) => a.localeCompare(b));

const rules = byName
  .map(([name, cp]) => `.${name}::before {\n  content: '\\${cp}';\n}`)
  .join('\n\n');

const css = `/*
 * Generated by scripts/build-icon-font.mjs — do not edit by hand.
 *
 * Font Awesome Free 6.5.1 Solid, subsetted to the ${glyphs.length} glyphs this app actually draws.
 * ${byName.length} class names map onto them: the codebase uses both v5 and v6 spellings for five icons,
 * so the alias has to keep working or eight call sites lose their glyph.
 *
 * Font Awesome Free 6.5.1 · CC BY 4.0 · https://fontawesome.com
 */

@font-face {
  font-family: 'Aucto Icons';
  font-style: normal;
  font-weight: 900;
  /*
   * block, not swap: these are private-use codepoints, so a fallback face has no glyph for them and swap would paint .notdef boxes.
   * Nothing shifts while it blocks, because these rules ship inside the render-blocking app stylesheet;
   *   the box is already the right size on the first frame and a late glyph paints into it.
   * That, not the font file, is what the 0.43 CLS on collection mobile was.
   */
  font-display: block;
  src: url('./fonts/aucto-icons.woff2') format('woff2');
}

/*
 * The declarations Font Awesome's base rule contributed, kept identical.
 *
 * \`line-height\` and \`display\` are why main.css imports this *before* the Tailwind utilities:
 * Font Awesome arrived as its own <link> and Vite injects the app stylesheet after it, so a sized icon has always taken Tailwind's line-height and an unsized one Font Awesome's 1.
 * Import this after the utilities and every sized icon shrinks — 20px to 14px at \`text-sm\`.
 */
.fa-solid {
  font-family: 'Aucto Icons';
  font-weight: 900;
  font-style: normal;
  font-variant: normal;
  line-height: 1;
  display: inline-block;
  text-rendering: auto;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

/* Applied and removed at runtime by the catalog's Refresh button (Collection.ts). */
.fa-spin {
  animation-name: fa-spin;
  animation-duration: 2s;
  animation-iteration-count: infinite;
  animation-timing-function: linear;
}

@keyframes fa-spin {
  0% {
    transform: rotate(0deg);
  }

  100% {
    transform: rotate(360deg);
  }
}

@media (prefers-reduced-motion: reduce) {
  .fa-spin {
    animation-delay: -1ms;
    animation-duration: 1ms;
    animation-iteration-count: 1;
    transition-delay: 0s;
    transition-duration: 0s;
  }
}

${rules}
`;

writeFileSync(OUT_CSS, css);
writeFileSync(
  OUT_MANIFEST,
  `${JSON.stringify(
    {
      source: 'Font Awesome Free 6.5.1 Solid',
      license: 'CC BY 4.0',
      generatedBy: 'scripts/build-icon-font.mjs',
      glyphs: glyphs.length,
      // Lets tests/icons.test.ts verify the font itself, not just the two text files beside it.
      // Without it an unstaged or stale woff2 passes every check while production serves @font-face pointing at nothing;
      //  blank boxes, nothing logged, under font-display: block.
      fontSha256: createHash('sha256').update(subset).digest('hex'),
      icons: Object.fromEntries(byName),
    },
    null,
    2
  )}\n`
);

const rel = (p) => relative(REPO_ROOT, p);
console.log(`${byName.length} classes over ${glyphs.length} glyphs`);
console.log(
  `${rel(OUT_FONT)}  ${source.length} B -> ${subset.length} B  (${Math.round((1 - subset.length / source.length) * 100)}% smaller)`
);
console.log(`${rel(OUT_CSS)}  ${css.length} B`);
console.log(`${rel(OUT_MANIFEST)}`);
